export function getGradeFromProfile(gradeString: string): number {
  if (!gradeString) return 2;
  if (gradeString.includes('PAUD') || gradeString.includes('TK')) return 0;
  if (gradeString.includes('1')) return 1;
  if (gradeString.includes('2')) return 2;
  if (gradeString.includes('3')) return 3;
  if (gradeString.includes('4')) return 4;
  if (gradeString.includes('5')) return 5;
  if (gradeString.includes('6')) return 6;
  return 2;
}

